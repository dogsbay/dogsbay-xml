package com.dogsbay.dogsbayaieditor.plugin.dita;

import static org.junit.jupiter.api.Assertions.*;
import static org.junit.jupiter.api.Assumptions.assumeTrue;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Comparator;
import java.util.Vector;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import com.dogsbay.dogsbayaieditor.grammar.GrammarProperties;
import com.dogsbay.dogsbayaieditor.properties.ConfigurationProperties;
import com.dogsbay.dogsbayaieditor.template.TemplateProperties;
import com.dogsbay.xml.DogsBayDocument;
import com.dogsbay.xml.XElement;

/**
 * Verifies that bundled DITA editing assets (DTDs, types, templates, catalog)
 * are extracted from the JAR and registered with ConfigurationProperties as
 * built-in (transient) entries — i.e. visible to consumers but never persisted
 * to user config.
 */
class DitaBuiltInAssetsTest {

    private Path tempHome;
    private File targetDir;

    @BeforeAll
    static void initDom4j() {
        // Required for DogsBayDocument to use the project's XElement implementation.
        System.setProperty("org.dom4j.factory", "com.dogsbay.xml.XDocumentFactory");
    }

    @BeforeEach
    void setUp() throws IOException {
        tempHome = Files.createTempDirectory("dita-builtin-test");
        targetDir = tempHome.resolve("dita-extract").toFile();
    }

    @AfterEach
    void tearDown() throws IOException {
        Files.walk(tempHome)
                .sorted(Comparator.reverseOrder())
                .map(Path::toFile)
                .forEach(File::delete);
    }

    @Test
    void extractsAllBundledFiles() throws IOException {
        DitaBuiltInAssets.extractIfNeeded(targetDir);

        assertTrue(new File(targetDir, "manifest.xml").isFile(), "manifest extracted");
        assertTrue(new File(targetDir, "version.txt").isFile(), "version marker extracted");
        assertTrue(new File(targetDir, "types/dita-concept.type").isFile(), "concept type extracted");
        assertTrue(new File(targetDir, "templates/dita-concept-template.xml").isFile(),
                "concept template extracted");
        assertTrue(new File(targetDir, "dtd/catalog.xml").isFile(), "DTD catalog extracted");
        assertTrue(new File(targetDir, "dtd/concept.dtd").isFile(), "concept DTD extracted");
        // Subdirectory under dtd/
        assertTrue(new File(targetDir, "dtd/mathml").isDirectory(),
                "mathml DTD subdirectory extracted");
    }

    @Test
    void skipsExtractionWhenVersionMatches() throws IOException {
        DitaBuiltInAssets.extractIfNeeded(targetDir);
        File marker = new File(targetDir, "version.txt");
        long firstMtime = marker.lastModified();

        // Force the mtime backwards so a re-extraction would be visible.
        assertTrue(marker.setLastModified(firstMtime - 60_000));

        DitaBuiltInAssets.extractIfNeeded(targetDir);
        assertEquals(firstMtime - 60_000, marker.lastModified(),
                "second call should not re-extract when version matches");
    }

    @Test
    void theBundledVersionSaysSomething() throws Exception {
        String version;
        try (java.io.InputStream in = DitaBuiltInAssets.class.getResourceAsStream("builtin/version.txt")) {
            assertNotNull(in, "the bundle must carry a version");
            version = new String(in.readAllBytes(), StandardCharsets.UTF_8).trim();
        }

        // It was an empty file. An empty bundled version compares equal to the empty one on disk, so the gate never fired:
        // the bundle was extracted once on a machine and never again, and a corrected DTD or template reached nobody who
        // had run the editor before. It is a digest of the bundle's contents now, generated by the build.
        assertFalse(version.isEmpty(), "an empty version can never differ from the copy on disk, so nothing refreshes");
        assertTrue(version.matches("[0-9a-f]{8,}"), "expected a digest, got: " + version);

        // and it is the digest of what the bundle actually contains, recomputed here by the same rules. Checking only
        // that it looks like a digest would pass on a stale one, which is the regression that brings the whole fault back.
        assertEquals(digestOfBundleSource(), version,
                "version.txt does not match the bundle's contents; the build's generateDitaBundleVersion task is the"
                        + " thing that keeps it in step");
    }

    /** The bundle's digest, by the same rules as the build's task: every file but the marker, sorted by relative path. */
    private static String digestOfBundleSource() throws Exception {
        java.nio.file.Path root = java.nio.file.Path.of(
                "src/main/resources/com/dogsbay/dogsbayaieditor/plugin/dita/builtin");
        assumeTrue(java.nio.file.Files.isDirectory(root), "runs from the checkout");
        java.security.MessageDigest digest = java.security.MessageDigest.getInstance("SHA-256");
        try (var walk = java.nio.file.Files.walk(root)) {
            walk.filter(java.nio.file.Files::isRegularFile)
                    .filter(f -> !f.getFileName().toString().equals("version.txt"))
                    .sorted(java.util.Comparator.comparing(f -> root.relativize(f).toString().replace('\\', '/')))
                    .forEach(f -> {
                        try {
                            digest.update(root.relativize(f).toString().replace('\\', '/')
                                    .getBytes(StandardCharsets.UTF_8));
                            digest.update(java.nio.file.Files.readAllBytes(f));
                        } catch (IOException e) {
                            throw new java.io.UncheckedIOException(e);
                        }
                    });
        }
        StringBuilder hex = new StringBuilder();
        for (byte b : digest.digest()) {
            hex.append(String.format("%02x", b));
        }
        return hex.substring(0, 16);
    }

    @Test
    void theMarkerIsWrittenOnlyOnceTheRestOfTheBundleIsThere() throws IOException {
        DitaBuiltInAssets.extractIfNeeded(targetDir);
        File marker = new File(targetDir, "version.txt");

        // An extraction that dies part way must not leave the new marker beside the old bundle: the gate would then skip
        // the repair for the life of that profile. Writing it last is what makes an interrupted upgrade recoverable, so
        // the marker must be the newest thing in the folder.
        long markerWritten = marker.lastModified();
        for (String name : new String[] { "manifest.xml", "dtd/catalog.xml", "types/dita-concept.type" }) {
            File file = new File(targetDir, name);
            assertTrue(file.isFile(), name + " should have been extracted");
            assertTrue(file.lastModified() <= markerWritten, name + " was written after the marker");
        }
    }

    @Test
    void asksAgainWhenTheSettingsFolderChanges() throws Exception {
        java.nio.file.Path first = targetDir.toPath().resolve("one");
        java.nio.file.Path second = targetDir.toPath().resolve("two");
        try {
            com.dogsbay.xml.properties.SettingsHome.setRoot(first.toString());
            DitaBuiltInAssets.ensureExtracted();
            assertTrue(new File(first.toFile(), "builtin/dita/version.txt").isFile());

            com.dogsbay.xml.properties.SettingsHome.setRoot(second.toString());
            DitaBuiltInAssets.ensureExtracted();

            // a flag saying the work was done would leave this one empty, and the headless validator would read past it
            assertTrue(new File(second.toFile(), "builtin/dita/version.txt").isFile(),
                    "a second settings folder in the same process must be populated too");
        } finally {
            com.dogsbay.xml.properties.SettingsHome.useDefault();
        }
    }

    @Test
    void theAssetsLiveUnderThisRunsSettingsFolder() throws Exception {
        java.nio.file.Path profile = targetDir.toPath().resolve("profile");
        com.dogsbay.xml.properties.SettingsHome.setRoot(profile.toString());
        try {
            // a run given a settings folder of its own must not read or write the user's built-ins
            assertEquals(profile.resolve("builtin").resolve("dita").toFile(), DitaBuiltInAssets.defaultTargetDir());
        } finally {
            com.dogsbay.xml.properties.SettingsHome.useDefault();
        }
        assertTrue(DitaBuiltInAssets.defaultTargetDir().toString()
                .startsWith(System.getProperty("user.home")), "and the default is still the user's own");
    }

    @Test
    void reExtractsWhenVersionDiffers() throws IOException {
        DitaBuiltInAssets.extractIfNeeded(targetDir);
        File marker = new File(targetDir, "version.txt");
        Files.write(marker.toPath(), "stale-version\n".getBytes(StandardCharsets.UTF_8));
        long stalemtime = marker.lastModified();
        assertTrue(marker.setLastModified(stalemtime - 60_000));

        DitaBuiltInAssets.extractIfNeeded(targetDir);
        assertNotEquals(stalemtime - 60_000, marker.lastModified(),
                "outdated version marker should trigger re-extraction");
        String fresh = new String(Files.readAllBytes(marker.toPath()), StandardCharsets.UTF_8).trim();
        assertNotEquals("stale-version", fresh);
    }

    @Test
    void registersTypesTemplatesAndCatalogAsTransientEntries() throws Exception {
        ConfigurationProperties config = newEmptyConfig();
        DitaBuiltInAssets.install(config, targetDir);

        // Catalog
        Vector catalogs = config.getCatalogs();
        boolean foundCatalog = false;
        for (Object c : catalogs) {
            String path = (String) c;
            if (path.endsWith("dtd/catalog.xml")
                    || path.endsWith("dtd" + File.separator + "catalog.xml")) {
                foundCatalog = true;
                break;
            }
        }
        assertTrue(foundCatalog, "DITA catalog should be registered. Got: " + catalogs);
        assertTrue(System.getProperty("xml.catalog.files", "").contains("catalog.xml"),
                "xml.catalog.files system property should be updated");

        // Grammar types — one for every kind the profile offers a template for
        assertEquals(12, countDitaGrammars(config),
                "should register 12 DITA grammar types. Got descriptions: "
                        + describeGrammars(config));

        // Templates — one per kind the tutorial needs, plus the three annotated topic variants
        assertEquals(16, countDitaTemplates(config),
                "should register 16 DITA templates. Got names: "
                        + describeTemplates(config));
    }

    @Test
    void duplicateRegistrationIsIdempotent() throws Exception {
        ConfigurationProperties config = newEmptyConfig();
        DitaBuiltInAssets.install(config, targetDir);
        DitaBuiltInAssets.install(config, targetDir);

        assertEquals(12, countDitaGrammars(config),
                "second install must not duplicate grammar entries");
        assertEquals(16, countDitaTemplates(config),
                "second install must not duplicate template entries");

        long ditaCatalogs = 0;
        for (Object c : config.getCatalogs()) {
            String path = (String) c;
            if (path.contains("dita") || path.contains("dtd")) {
                ditaCatalogs++;
            }
        }
        assertTrue(ditaCatalogs >= 1, "catalog registered");
    }

    /**
     * Counted by what the profile registered, not by what the type is called.
     *
     * <p>"DITA 1.3" was a reliable marker while every type was a DITA document type. Two of them are not: a DITAVAL
     * filter has no DITA version of its own, and a Schematron rule set is not DITA at all — both are files a DITA
     * project needs beside its content. Counting by name would have quietly counted neither.
     */
    private static int countDitaGrammars(ConfigurationProperties config) {
        int count = 0;
        for (Object g : config.getGrammarProperties()) {
            String systemId = ((GrammarProperties) g).getSystemID();
            String description = ((GrammarProperties) g).getDescription();
            boolean dita = systemId != null && !systemId.isBlank();
            boolean besideIt = "DITA Conditional Filter (DITAVAL)".equals(description)
                    || "Schematron Rules".equals(description);
            if (dita || besideIt) count++;
        }
        return count;
    }

    /**
     * Counted by where the file is, not by its name.
     *
     * <p>Templates used to be named after their files, so "dita-" was a reliable marker. They carry the manifest's own
     * name now — "Key Definition Map" rather than "dita-keydef-map-minimal" — and counting by name would quietly count
     * none of them.
     */
    private static int countDitaTemplates(ConfigurationProperties config) {
        int count = 0;
        for (Object t : config.getTemplateProperties()) {
            java.net.URL url = ((TemplateProperties) t).getURL();
            if (url != null && url.toString().contains("/templates/dita-")) count++;
        }
        return count;
    }

    private static java.util.List<String> describeGrammars(ConfigurationProperties config) {
        java.util.List<String> names = new java.util.ArrayList<>();
        for (Object g : config.getGrammarProperties()) {
            names.add(((GrammarProperties) g).getDescription());
        }
        return names;
    }

    private static java.util.List<String> describeTemplates(ConfigurationProperties config) {
        java.util.List<String> names = new java.util.ArrayList<>();
        for (Object t : config.getTemplateProperties()) {
            names.add(((TemplateProperties) t).getName());
        }
        return names;
    }

    @Test
    void builtInEntriesAreNotPersisted() throws Exception {
        ConfigurationProperties config = newEmptyConfig();
        int grammarsBefore = countPersistedChildren(config, "grammar-properties");
        int templatesBefore = countPersistedChildren(config, "template-properties");

        DitaBuiltInAssets.install(config, targetDir);

        // The persisted XElement model under config should not have grown:
        // built-in entries live in transient in-memory lists, not in the document.
        assertEquals(grammarsBefore, countPersistedChildren(config, "grammar-properties"),
                "built-in grammars must not appear in persisted XML");
        assertEquals(templatesBefore, countPersistedChildren(config, "template-properties"),
                "built-in templates must not appear in persisted XML");
    }

    // -------------------------------------------------------------------------

    private static ConfigurationProperties newEmptyConfig() throws Exception {
        XElement root = new XElement("dogsbay");
        root.setText("\n");
        DogsBayDocument doc = new DogsBayDocument(
                Path.of(System.getProperty("java.io.tmpdir"),
                        "test-config-" + System.nanoTime() + ".xml")
                        .toUri().toURL(),
                root);
        return new ConfigurationProperties(doc) {
            @Override public void save() { /* no-op for tests */ }
            @Override public void saveToDisk() { /* no-op for tests */ }
        };
    }

    private static int countPersistedChildren(ConfigurationProperties config, String elementName) {
        XElement root = (XElement) config.getElement();
        if (root == null) return 0;
        XElement[] children = root.getElements(elementName);
        return children == null ? 0 : children.length;
    }
}
